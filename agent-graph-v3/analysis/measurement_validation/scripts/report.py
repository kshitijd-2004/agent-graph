#!/usr/bin/env python3.11
"""Generate the validation reports and the figure set.

Every number this module emits carries:
  * its DENOMINATOR,
  * its SAMPLE COMPONENT (A representative / B targeted — never pooled into
    one population claim),
  * its INTERVAL (Wilson/Clopper-Pearson unweighted, or cluster bootstrap for
    anything design-weighted),
  * an ``insufficient`` flag when the effective sample size is too small.

Reports are written as Markdown (for reading) plus JSON (for reuse), so a
number in prose and a number in a table cannot drift apart.

Usage:
    python3.11 analysis/measurement_validation/scripts/report.py \
        --stage extractor_only
"""
from __future__ import annotations

import argparse
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import common as C  # noqa: E402
import stats_v1 as S  # noqa: E402

REPORTS = C.REPORTS_DIR
DESIGN_PATH = os.path.join(C.VALIDATION_ROOT, 'SAMPLING_DESIGN.json')
PAIR_DESIGN = os.path.join(C.VALIDATION_ROOT, 'PAIR_DESIGN.json')
SAMPLE = os.path.join(C.VALIDATION_ROOT, 'sample_manifest.jsonl')
PAIRS = os.path.join(C.VALIDATION_ROOT, 'pair_manifest.jsonl')
EV = os.path.join(C.CACHE_DIR, 'extraction_evidence.jsonl')


def _md_table(headers, rows):
    out = ['| ' + ' | '.join(headers) + ' |',
           '|' + '|'.join('---' for _ in headers) + '|']
    for r in rows:
        out.append('| ' + ' | '.join(str(x) for x in r) + ' |')
    return '\n'.join(out)


def _fmt(v, nd=3):
    if v is None:
        return '—'
    if isinstance(v, float):
        return f'{v:.{nd}f}'
    return str(v)


def report_sample(summary, outdir=REPORTS):
    C.ensure_dir(outdir)
    d = C.read_json(DESIGN_PATH) if os.path.isfile(DESIGN_PATH) else {}
    sample = C.read_jsonl(SAMPLE) if os.path.isfile(SAMPLE) else []
    counts = d.get('counts', {})
    frame = d.get('frame', {})
    L = []
    A = L.append
    A('# Validation sample — construction record\n')
    A('Generated by `scripts/report.py`. Every figure below is reproducible '
      'from the recorded seed; see `SAMPLING.md` for the design rationale.\n')
    A('## Population frame\n')
    A(f"- Source: `{frame.get('source')}`")
    A(f"- Measurement rows in frame: **{frame.get('n_measurement_rows')}**")
    A(f"- Unique trace ids: **{frame.get('n_unique_trace_ids')}**")
    A(f"- Trace ids appearing twice (distinct attempts): "
      f"**{frame.get('n_ambiguous_trace_ids')}**")
    A(f"- Population definition: {frame.get('population_definition')}\n")
    A('Explicitly **not** the same population as:')
    for x in frame.get('not_the_same_population_as', []):
        A(f'- `{x}`')
    A('')
    A('## Sample composition\n')
    A(_md_table(['slice', 'n'], [
        ['total units', counts.get('total_units')],
        ['component A (representative)', counts.get('A_representative')],
        ['component B (targeted, error-enriched)', counts.get('B_targeted')],
        ['LEP executions', counts.get('lep')],
        ['benign controls', counts.get('benign')],
    ]))
    A('')
    A('### By task family and kind\n')
    A(_md_table(['family \\| kind', 'n'], [
        [k.replace('|', ' / '), v]
        for k, v in sorted((counts.get('by_family_and_kind') or {}).items())]))
    A('')
    A('### By topology\n')
    A(_md_table(['topology', 'n'],
                sorted((counts.get('by_topology') or {}).items())))
    A('')
    A('### By LEP (LEP executions only)\n')
    A(_md_table(['LEP', 'n'], sorted((counts.get('by_lep') or {}).items())))
    A('')
    A('### By propagation mode\n')
    A(_md_table(['mode', 'n'],
                sorted((counts.get('by_propagation_mode') or {}).items())))
    A('')
    A('### Targeted strata membership\n')
    A('A unit can belong to several targeted strata; membership counts '
      'therefore sum to more than the component B size.\n')
    A(_md_table(['targeted predicate', 'n units'],
                sorted((counts.get('targeted_predicate_membership') or {}
                        ).items(), key=lambda x: -x[1])))
    A('')
    A('## Constraints respected\n')
    for k, v in (d.get('constraints_respected') or {}).items():
        A(f'- **{k}**: {v}')
    A('')
    C.write_text(os.path.join(outdir, 'sample_report.md'), '\n'.join(L))
    return '\n'.join(L)


def report_coverage(outdir=REPORTS):
    """The extraction-coverage finding — the single most consequential number
    this framework produces, because it bounds what the BND comparison can
    possibly be measuring."""
    C.ensure_dir(outdir)
    p = os.path.join(outdir, 'extraction_coverage_by_family.json')
    if not os.path.isfile(p):
        return None
    cov = C.read_json(p)
    L = []
    A = L.append
    A('# Extraction coverage by task family\n')
    A('Fraction of sampled LEP executions whose FINAL DELIVERABLE is actually '
      '`observed` by each extractor. Family-appropriate deliverable fields '
      'are used (financial: final numeric answer; research: per-claim '
      'verdicts; code review: per-issue stances).\n')
    A(_md_table(
        ['task family', 'n units', 'frozen observed', 'v6 observed',
         'both', 'neither', 'v6 − frozen'],
        [[r['task_family'], r['n_units'],
          _fmt(r['frozen_deliverable_observed_rate']),
          _fmt(r['v6_deliverable_observed_rate']),
          _fmt(r['both_observed_rate']), _fmt(r['neither_observed_rate']),
          f"{r['coverage_gap_pp']:+.1f} pp"] for r in cov]))
    A('')
    A('## Interpretation\n')
    A('A row whose deliverable is not `observed` cannot be compared on the '
      'deliverable content; the BND distance for that row is therefore driven '
      'by whichever dimensions still have values (typically `actions` and '
      '`outcomes`). This is a **coverage** fact, not an accuracy fact, and it '
      'is reported separately from precision and recall.\n')
    A('The framework never treats an `unavailable` extraction as a correct '
      'negative, and never collapses it into "no divergence".\n')
    C.write_text(os.path.join(outdir, 'extraction_coverage.md'), '\n'.join(L))
    return '\n'.join(L)


def report_pairs(outdir=REPORTS):
    C.ensure_dir(outdir)
    if not os.path.isfile(PAIR_DESIGN):
        return None
    d = C.read_json(PAIR_DESIGN)
    c = d.get('counts', {})
    L = []
    A = L.append
    A('# Matched-pair validation set\n')
    A(f"Pairs: **{d.get('n_pairs')}** "
      f"(target {d.get('n_per_family_target')} per family)\n")
    A('## Composition by required class\n')
    A(_md_table(['class', 'description', 'n'],
                [[k, dict((x['name'], x['description'])
                          for x in d.get('classes', [])).get(k, ''), v]
                 for k, v in sorted((c.get('by_class') or {}).items())]))
    A('')
    A('## Coverage of the required axes\n')
    A(_md_table(['axis', 'n'], [
        ['reusing units from the 300-trace sample',
         c.get('reusing_300_sample_units')],
        ['distinct benign references used',
         c.get('distinct_benign_references_used')],
        ['pairs with the full 3-reference set',
         c.get('pairs_with_3_references')],
        ['pairs with >1 reference (multi-reference semantics apply)',
         c.get('pairs_with_multiple_references')],
        ['pairs carrying a known-duplicate trace_id',
         c.get('pairs_with_ambiguous_trace_id')],
    ]))
    A('')
    A('## Multi-reference semantics\n')
    ms = d.get('multi_reference_semantics', {})
    A(ms.get('statement', ''))
    A('')
    A('Pipeline algorithm reproduced for every pair:\n')
    for s in ms.get('pipeline_algorithm_reproduced_here', []):
        A(f'1. {s}')
    A('')
    A('### How annotator judgments map onto the pipeline semantics\n')
    for k, v in (ms.get('how_annotator_judgments_map_on') or {}).items():
        A(f'- **{k}**: {v}')
    A('')
    A('### Explicitly not done\n')
    for s in ms.get('explicitly_not_done', []):
        A(f'- {s}')
    A('')
    C.write_text(os.path.join(outdir, 'pair_report.md'), '\n'.join(L))
    return '\n'.join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--stage', default='extractor_only')
    ap.add_argument('--outdir', default=REPORTS)
    a = ap.parse_args()
    C.ensure_dir(a.outdir)
    report_sample(None, a.outdir)
    report_coverage(a.outdir)
    report_pairs(a.outdir)
    ev = os.path.join(a.outdir, 'extractor_vs_extractor.json')
    if os.path.isfile(ev):
        report_extractor(a.outdir)
    print(f'reports written to {a.outdir}')
    for f in sorted(os.listdir(a.outdir)):
        print(' ', f)


def report_extractor(outdir=REPORTS):
    agree = C.read_json(os.path.join(outdir, 'extractor_vs_extractor.json'))
    grades = C.read_json(os.path.join(outdir,
                                      'grading_agreement_by_family.json'))
    deliv = C.read_json(os.path.join(outdir,
                                     'deliverable_agreement_by_family.json'))
    L = []
    A = L.append
    A('# Extractor-vs-extractor comparison (no human labels required)\n')
    A(f"Units processed: **{agree['n_units']}**, successful: "
      f"**{agree['n_ok']}**, errors: **{agree['n_errors']}**\n")
    A('## Deliverable-level agreement\n')
    A('Restricted to the family-appropriate final deliverable. '
      '`one_unavailable` is kept separate from `value_differs`: one extractor '
      'not looking is not a disagreement about content, and is not agreement '
      'either.\n')
    rows = []
    for r in deliv:
        oc = r['outcome_rates']
        rows.append([r['task_family'], r['n_units'], r['n_deliverable_items'],
                     _fmt(oc.get('exact_match', 0)),
                     _fmt(oc.get('value_differs', 0)),
                     _fmt(oc.get('state_differs', 0)),
                     _fmt(oc.get('one_unavailable', 0)),
                     _fmt(oc.get('both_unavailable', 0))])
    A(_md_table(['family', 'n units', 'n items', 'exact', 'value differs',
                 'state differs', 'one unavailable', 'both unavailable'], rows))
    A('')
    A('## Grading agreement\n')
    A(_md_table(['family', 'n', 'both gradeable', 'agreement on gradeable',
                 'frozen gradeable rate', 'v6 gradeable rate'],
                [[r['task_family'], r['n_units'], r['n_both_gradeable'],
                  _fmt(r['grade_agreement_on_gradeable']),
                  _fmt(r['frozen_gradeable_rate']),
                  _fmt(r['v6_gradeable_rate'])] for r in grades]))
    A('')
    A('## What this does and does not establish\n')
    A('This section establishes **how much the two extractors differ from '
      'each other**. It cannot establish which of them is correct: that '
      'requires the human labels of Phase B. A high disagreement rate here is '
      'a reason to expect the human-grounded evaluation to matter, not a '
      'result about measurement validity.\n')
    C.write_text(os.path.join(outdir, 'extractor_comparison.md'), '\n'.join(L))
    return '\n'.join(L)


if __name__ == '__main__':
    main()
